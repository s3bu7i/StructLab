  function setText(selector, value) {
    const el = document.querySelector(selector);
    if (el) el.textContent = value;
  }

  function setHTML(selector, value) {
    const el = document.querySelector(selector);
    if (el) el.innerHTML = value;
  }

  function setAllText(selector, values) {
    document.querySelectorAll(selector).forEach((el, index) => {
      if (values[index] !== undefined) el.textContent = values[index];
    });
  }

  function setIconTexts(selector, values) {
    document.querySelectorAll(selector).forEach((el, index) => {
      if (values[index] === undefined) return;
      const icon = el.querySelector('svg');
      el.innerHTML = icon ? `${icon.outerHTML} ${values[index]}` : values[index];
    });
  }

  function setSidebarLabels(selector, labels) {
    document.querySelectorAll(selector).forEach((item, index) => {
      if (labels[index] === undefined) return;
      const topIcons = item.querySelectorAll(':scope > svg');
      const firstIcon = topIcons[0] ? topIcons[0].outerHTML : '';
      const trailingIcon = topIcons.length > 1 ? topIcons[topIcons.length - 1].outerHTML : '';
      const badge = item.querySelector(':scope > .sidebar-badge');
      item.innerHTML = `${firstIcon} ${labels[index]}${badge ? badge.outerHTML : ''}${trailingIcon ? ' ' + trailingIcon : ''}`;
    });
  }

