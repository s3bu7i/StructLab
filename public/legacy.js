  function syncCourseMetadata() {
    document.querySelectorAll('#courses .course-card').forEach(card => {
      const title = card.querySelector('h3')?.textContent || '';
      const author = card.querySelector('.course-author')?.textContent || '';
      const badges = Array.from(card.querySelectorAll('.badge')).map(el => el.textContent).join(' ');
      const description = card.querySelector('.course-description')?.textContent || '';
      const meta = Array.from(card.querySelectorAll('.course-meta span')).map(el => el.textContent).join(' ');
      card.dataset.searchText = [title, author, badges, description, meta, card.dataset.keywords || ''].join(' ').toLowerCase();
    });
  }

  function updateCourseStatus(visibleCount, totalCount, query) {
    const extra = getExtraTranslations();
    const status = document.getElementById('courseStatus');
    if (!status) return;
    const template = query ? extra.featured.statusQuery : extra.featured.statusAll;
    status.textContent = template
      .replace('{count}', String(visibleCount))
      .replace('{total}', String(totalCount))
      .replace('{query}', query);
  }

  function applyCourseControls() {
    syncCourseMetadata();
    const grid = document.querySelector('#courses .courses-grid');
    const cards = Array.from(document.querySelectorAll('#courses .course-card'));
    const filter = document.querySelector('.filter-tab.active')?.dataset.filter || 'all';
    const query = (document.getElementById('courseSearch')?.value || '').trim().toLowerCase();
    const sortValue = document.getElementById('courseSort')?.value || 'default';

    const matched = cards.filter(card => {
      const matchesFilter = filter === 'all' || card.dataset.level === filter;
      const matchesQuery = !query || (card.dataset.searchText || '').includes(query);
      return matchesFilter && matchesQuery;
    });

    const sorted = [...matched];
    if (sortValue === 'az') {
      sorted.sort((a, b) => (a.querySelector('h3')?.textContent || '').localeCompare(b.querySelector('h3')?.textContent || '', currentLang));
    } else if (sortValue === 'students') {
      sorted.sort((a, b) => Number(b.dataset.students || 0) - Number(a.dataset.students || 0));
    } else if (sortValue === 'duration') {
      sorted.sort((a, b) => Number(a.dataset.duration || 0) - Number(b.dataset.duration || 0));
    }

    const hidden = cards.filter(card => !matched.includes(card));
    [...sorted, ...hidden].forEach(card => grid.appendChild(card));
    cards.forEach(card => card.classList.toggle('hidden', !matched.includes(card)));

    const emptyState = document.getElementById('courseEmpty');
    if (emptyState) emptyState.classList.toggle('show', matched.length === 0);
    updateCourseStatus(matched.length, cards.length, query);
  }

